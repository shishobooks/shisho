package migrations

import (
	"context"

	"github.com/pkg/errors"
	"github.com/uptrace/bun"
)

func init() {
	up := func(ctx context.Context, db *bun.DB) error {
		// The order a Page-based File's pages run in. NULL means left to
		// right, as it does for every File the scanner has no direction for.
		statements := []string{
			`ALTER TABLE files ADD COLUMN reading_direction TEXT`,
			`ALTER TABLE files ADD COLUMN reading_direction_source TEXT`,
		}
		for _, statement := range statements {
			if _, err := db.ExecContext(ctx, statement); err != nil {
				return errors.WithStack(err)
			}
		}
		return nil
	}

	down := func(ctx context.Context, db *bun.DB) error {
		statements := []string{
			`ALTER TABLE files DROP COLUMN reading_direction_source`,
			`ALTER TABLE files DROP COLUMN reading_direction`,
		}
		for _, statement := range statements {
			if _, err := db.ExecContext(ctx, statement); err != nil {
				return errors.WithStack(err)
			}
		}
		return nil
	}

	Migrations.MustRegister(up, down)
}
